const validateCatalogSize = (
    label: string,
    actual: number,
    expected: number,
): void => {
    if (actual === expected) return;
    throw new Error(
        `[AvatarPartCatalog] ${label}=${actual}, expected ${expected}`,
    );
};

validateCatalogSize(
    "faces",
    AVATAR_FACE_SHAPES.length,
    AVATAR_FACE_SHAPE_COUNT,
);
validateCatalogSize("hair", AVATAR_HAIR_SHAPES.length, AVATAR_HAIR_SHAPE_COUNT);
validateCatalogSize("eyes", AVATAR_EYE_SHAPES.length, AVATAR_EYE_SHAPE_COUNT);
